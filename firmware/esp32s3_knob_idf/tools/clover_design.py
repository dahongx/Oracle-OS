# -*- coding: utf-8 -*-
"""Design the smooth, hi-res four-leaf clover used as the spinning talisman
in the mini-games (distinct from the chunky pixel clover on the cat's tail).

Draw four heart leaves (+-arrangement, tips meeting at centre) supersampled for
clean anti-aliased edges, so it rotates smoothly via lv_image_set_rotation.
Green leaf + dark-green rim + soft highlight + pale-gold centre, on transparent.
Outputs a preview PNG and (when --emit) the LVGL ARGB8888 C array.
"""
import math
import sys
from PIL import Image, ImageDraw, ImageFilter

S = 100                 # final size (px), the on-screen clover source resolution
SS = 4                  # supersample factor
D = S * SS              # draw resolution

GREEN = (127, 176, 105, 255)   # leaf fill
DARK = (74, 107, 58, 255)      # leaf rim / vein
HI = (168, 205, 140, 255)      # soft highlight
GOLD = (232, 212, 138, 255)    # pale centre


def heart_points(scale, n=140):
    """Classic parametric heart, tip pointing DOWN, centred at origin."""
    pts = []
    for i in range(n):
        t = 2 * math.pi * i / n
        x = 16 * math.sin(t) ** 3
        y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
        pts.append((x * scale, -y * scale))   # flip y: tip (min y) goes to bottom
    return pts


def make_leaf():
    """A single heart leaf tile (tip pointing DOWN), RGBA, transparent bg."""
    L = int(D * 0.52)
    tile = Image.new("RGBA", (L, L), (0, 0, 0, 0))
    td = ImageDraw.Draw(tile)
    scale = L / 42.0
    cx, cy = L * 0.5, L * 0.44
    pts = [(cx + px, cy + py) for px, py in heart_points(scale)]
    td.polygon(pts, fill=GREEN, outline=DARK)
    # thicken rim a touch by redrawing outline offset
    td.line(pts + [pts[0]], fill=DARK, width=max(2, SS))
    # soft highlight: a smaller heart, upper-left, lighter
    hp = [(cx + px * 0.55 - L * 0.10, cy + py * 0.55 - L * 0.10) for px, py in heart_points(scale)]
    td.polygon(hp, fill=HI)
    return tile


def main():
    img = Image.new("RGBA", (D, D), (0, 0, 0, 0))
    leaf = make_leaf()
    L = leaf.size[0]
    c = D // 2
    off = int(D * 0.19)                 # how far each leaf sits from centre
    # (rotation CCW, offset vector) so every tip points inward to the centre
    placements = [
        (0,   (0, -off)),   # north leaf, tip down
        (180, (0,  off)),   # south leaf, tip up
        (270, (off, 0)),    # east leaf,  tip left
        (90,  (-off, 0)),   # west leaf,  tip right
    ]
    for ang, (dx, dy) in placements:
        rot = leaf.rotate(ang, resample=Image.BICUBIC, expand=True)
        px = c + dx - rot.size[0] // 2
        py = c + dy - rot.size[1] // 2
        img.alpha_composite(rot, (px, py))

    # pale-gold centre
    dr = ImageDraw.Draw(img)
    rr = int(D * 0.07)
    dr.ellipse((c - rr, c - rr, c + rr, c + rr), fill=GOLD)

    # downscale with AA
    out = img.resize((S, S), Image.LANCZOS)

    # preview on black
    prev = Image.new("RGBA", (S * 3, S), (0, 0, 0, 255))
    prev.alpha_composite(out.resize((S, S)), (0, 0))
    # show a rotated copy to check spin cleanliness
    prev.alpha_composite(out.rotate(27, resample=Image.BICUBIC), (S, 0))
    prev.alpha_composite(out.rotate(45, resample=Image.BICUBIC), (S * 2, 0))
    prev.convert("RGB").save("tools/clover_preview.png")
    print("wrote tools/clover_preview.png  size=", out.size)

    if "--emit" in sys.argv:
        emit(out)


def emit(out):
    px = out.load()
    # LVGL ARGB8888 byte order in memory: B, G, R, A
    data = bytearray()
    for y in range(S):
        for x in range(S):
            r, g, b, a = px[x, y]
            data += bytes((b, g, r, a))
    with open("main/ui/clover_img.c", "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/clover_design.py -- do not edit.\n")
        f.write("// Smooth four-leaf clover, ARGB8888 (byte order B,G,R,A).\n")
        f.write("#include <stdint.h>\n\n")
        f.write("const uint8_t clover_map[] = {\n")
        for i in range(0, len(data), 20):
            f.write("    " + ",".join(str(v) for v in data[i:i + 20]) + ",\n")
        f.write("};\n")
    with open("main/ui/clover_img.hpp", "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/clover_design.py -- do not edit.\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write('extern "C" const uint8_t clover_map[];\n\n')
        f.write("namespace clover_img {\n")
        f.write(f"inline constexpr int W = {S};\n")
        f.write(f"inline constexpr int H = {S};\n")
        f.write("}  // namespace clover_img\n")
    print(f"wrote main/ui/clover_img.c ({len(data)} bytes) + clover_img.hpp")


main()
