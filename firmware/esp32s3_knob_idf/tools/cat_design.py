# -*- coding: utf-8 -*-
"""Design the Oracle OS pixel cat mascot.
Draw at low logical resolution with primitives, derive a clean 1px outline,
place face details, then preview exactly as it will look on-device
(black background, gold outline, dim-gold fill, bright-gold eyes).
Outputs a big nearest-neighbour PNG to eyeball, and prints the grid.
"""
from PIL import Image, ImageDraw

W, H = 30, 25

# --- 1. build a filled silhouette mask at logical resolution ---
mask = Image.new("1", (W, H), 0)
d = ImageDraw.Draw(mask)

# head (round)
d.ellipse((6, 4, 19, 15), fill=1)
# ears (triangles rising from the head top)
d.polygon([(7, 7), (8, 1), (12, 6)], fill=1)           # left ear
d.polygon([(18, 7), (17, 1), (13, 6)], fill=1)         # right ear
# body (sitting loaf, a touch narrower than the head -> visible shoulders)
d.ellipse((7, 13, 18, 24), fill=1)
d.rectangle((7, 19, 18, 24), fill=1)                   # square off the base
d.ellipse((6, 20, 12, 24), fill=1)                     # left haunch
d.ellipse((13, 20, 19, 24), fill=1)                    # right haunch
# tail curling up the right side, reaching up toward the clover
d.line([(18, 23), (22, 22), (24, 18), (24, 13)], fill=1, width=2)

fill = [[1 if mask.getpixel((x, y)) else 0 for x in range(W)] for y in range(H)]

# --- 2. char grid: '.' fill, '#' outline (fill cell touching empty) ---
grid = [[' '] * W for _ in range(H)]


def empty(x, y):
    return x < 0 or y < 0 or x >= W or y >= H or fill[y][x] == 0


for y in range(H):
    for x in range(W):
        if not fill[y][x]:
            continue
        edge = any(empty(x + dx, y + dy) for dx, dy in
                   ((1, 0), (-1, 0), (0, 1), (0, -1)))
        grid[y][x] = '#' if edge else '.'

# --- 3. face details (overwrite interior fill) ---
def put(x, y, c):
    if 0 <= x < W and 0 <= y < H:
        grid[y][x] = c

# eyes (dark, so they read on the light fill)
for ex in (10, 15):
    put(ex, 9, 'o')
    put(ex, 10, 'o')
# nose (single soft pink dot)
put(12, 11, '^')
put(13, 11, '^')
# cheeks (subtle blush)
put(8, 11, '*')
put(17, 11, '*')

# --- 3b. lucky four-leaf clover at the tail tip (hand-authored pixels) ---
# Four rounded lobes split by a cross gap so all four leaves read clearly;
# 'g' leaf green, 'G' dark-green rim (bottom/right of each lobe = depth),
# 'y' pale centre. The gold tail curls up to meet its base.
CLOVER = [
    ".g...g.",
    "ggg.ggg",
    "gggGgGg",
    "..GyG..",
    "gGgGggg",
    "ggg.ggg",
    ".G...G.",
]
cx0, cy0 = 20, 5
for j, crow in enumerate(CLOVER):
    for i, ch in enumerate(crow):
        if ch != '.':
            put(cx0 + i, cy0 + j, ch)
put(23, 12, '#')  # short stem linking the clover down onto the tail

# --- preview render ---
PAL = {
    ' ': (0, 0, 0, 0),
    '#': (200, 169, 106, 255),   # gold outline
    '.': (237, 232, 216, 255),   # cream fill (like the mockup's white cat)
    'o': (34, 30, 24, 255),      # dark eyes
    '^': (214, 150, 140, 255),   # pink nose
    '*': (222, 186, 170, 255),   # soft cheek blush
    'g': (127, 176, 105, 255),   # clover leaf green
    'G': (74, 107, 58, 255),     # clover dark-green outline
    'y': (232, 212, 138, 255),   # clover pale centre
}
S = 20
prev = Image.new("RGBA", (W * S, H * S), (0, 0, 0, 255))
pd = ImageDraw.Draw(prev)
for y in range(H):
    for x in range(W):
        c = grid[y][x]
        if c == ' ':
            continue
        pd.rectangle((x * S, y * S, x * S + S - 1, y * S + S - 1), fill=PAL[c])
# faint pixel grid for inspection
for gx in range(W + 1):
    pd.line([(gx * S, 0), (gx * S, H * S)], fill=(40, 40, 40, 255))
for gy in range(H + 1):
    pd.line([(0, gy * S), (W * S, gy * S)], fill=(40, 40, 40, 255))
prev.save("tools/cat_preview.png")

print("W,H =", W, H)
for row in grid:
    print(''.join(row))

# --- 4. emit C++ art data (pad every row to W) ---
rows = [''.join(r).ljust(W) for r in grid]
with open("main/ui/cat_art.hpp", "w", encoding="utf-8") as f:
    f.write("// Auto-generated by tools/cat_design.py -- do not edit by hand.\n")
    f.write("// Oracle OS pixel cat mascot.\n")
    f.write("// Legend: ' ' transparent  '#' outline  '.' fill  'o' eye  '^' nose"
            "  '*' cheek  'g' clover  'G' clover-edge  'y' clover-centre\n")
    f.write("#pragma once\n\n")
    f.write("namespace cat_art {\n")
    f.write(f"inline constexpr int W = {W};\n")
    f.write(f"inline constexpr int H = {H};\n")
    f.write("inline constexpr const char* ROWS[H] = {\n")
    for r in rows:
        esc = r.replace('\\', '\\\\').replace('"', '\\"')
        f.write(f'    "{esc}",\n')
    f.write("};\n")
    f.write("}  // namespace cat_art\n")
print("wrote main/ui/cat_art.hpp")

